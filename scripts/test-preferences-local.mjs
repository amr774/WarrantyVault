// Real browser validation. Creates only a new verification account/product and keeps them.
import { chromium, expect } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { randomBytes } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { scannerTestDatabase } from './scanner-test-db.mjs';
const baseURL = 'http://localhost:4174';
const browser = await chromium.launch();
const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 960 } });
context.setDefaultTimeout(30000);
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const db = new PrismaClient({ datasources: { db: { url: scannerTestDatabase() } } });
let user;
const report = { testedAt: new Date().toISOString(), checks: [] };
async function noOverflow() { expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true); }
try {
  await page.goto('/login');
  await page.getByRole('button', { name: 'Switch to Arabic' }).click();
  await expect(page.getByRole('heading', { name: 'مرحبًا بعودتك.' })).toBeVisible();
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl');
  await page.getByRole('button', { name: 'التبديل إلى الإنجليزية' }).click();
  const response = await context.request.post('/api/auth/register', { headers: { Origin: baseURL }, data: {
    name: 'Language verification', email: `display-${Date.now()}@example.com`, password: randomBytes(24).toString('base64url'),
  } });
  expect(response.status(), await response.text()).toBe(201);
  user = await response.json();
  await page.goto('/app/settings');
  await page.getByRole('button', { name: 'Dark', exact: true }).click();
  await expect(page.locator('html')).toHaveClass('dark');
  await page.getByRole('button', { name: 'العربية', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'الإعدادات', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'المظهر واللغة' })).toBeVisible();
  await expect(page.locator('html')).toHaveClass('dark');
  await expect(page.locator('html')).toHaveAttribute('lang', 'ar');
  const sidebar = await page.locator('.sidebar').boundingBox();
  expect(sidebar.x).toBeGreaterThan(1100);
  await noOverflow();
  await page.screenshot({ path: '.data/display-ar-dark-desktop.png', fullPage: true, animations: 'disabled' });
  report.checks.push('Login translation, saved language/theme, Arabic RTL sidebar and desktop dark appearance');
  await page.goto('/app/products/new');
  await page.getByLabel('اسم المنتج *', { exact: true }).fill('My unchanged Camera A1');
  await page.getByRole('button', { name: 'التبديل إلى الإنجليزية' }).click();
  await expect(page.getByLabel('Product name *', { exact: true })).toHaveValue('My unchanged Camera A1');
  await page.getByRole('button', { name: 'Switch to Arabic' }).click();
  await expect(page.getByLabel('اسم المنتج *', { exact: true })).toHaveValue('My unchanged Camera A1');
  await page.getByLabel('الفئة *').selectOption({ label: 'إلكترونيات' });
  await page.getByLabel('تاريخ الشراء *', { exact: true }).fill('2026-10-25');
  await page.getByLabel('مدة الضمان بالشهور *', { exact: true }).fill('12');
  await page.getByRole('button', { name: 'إضافة إلى خزنتي', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'My unchanged Camera A1', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'تغطية الضمان' })).toBeVisible();
  await expect(page.locator('.detail-grid')).toContainText(/٢٥.*١٠.*٢٠٢٦/);
  report.checks.push('Arabic product form, category choices, creation, localized dates and user content preserved during language switches');
  await page.goto('/app/settings');
  await page.getByRole('button', { name: 'فاتح', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('html')).not.toHaveClass('dark');
  await noOverflow();
  await page.getByRole('button', { name: 'فتح القائمة' }).click();
  await expect(page.getByRole('link', { name: 'الإعدادات', exact: true })).toBeVisible();
  const mobileSidebar = await page.locator('.sidebar').boundingBox();
  expect(mobileSidebar.x).toBeGreaterThan(100);
  await page.getByRole('button', { name: 'إغلاق القائمة' }).click();
  await expect(page.locator('.sidebar')).not.toBeInViewport();
  await page.screenshot({ path: '.data/display-ar-light-mobile.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'داكن', exact: true }).click();
  await page.screenshot({ path: '.data/display-ar-dark-mobile.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('dir', 'ltr');
  await page.getByRole('button', { name: 'Light', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible();
  await expect(page.locator('html')).not.toHaveClass('dark');
  await noOverflow();
  await page.screenshot({ path: '.data/display-en-light-mobile.png', fullPage: true, animations: 'disabled' });
  report.checks.push('Mobile RTL navigation, both color themes, switch back to English/LTR, persistence after reload and no horizontal overflow');
  await page.goto('/app/scan');
  await page.getByRole('button', { name: 'Switch to Arabic' }).click();
  await page.getByLabel('رفع مستند للمسح').setInputFiles('tests/fixtures/ocr/english.png');
  await page.getByRole('button', { name: 'بدء المسح' }).click();
  await expect(page.getByRole('heading', { name: 'راجع البيانات قبل الحفظ' })).toBeVisible({ timeout: 190000 });
  await expect(page.getByLabel('اسم المنتج', { exact: true })).toHaveValue('Studio Headphones');
  await expect(page.getByLabel('تاريخ انتهاء الضمان')).toHaveValue('2027-10-15');
  report.checks.push('Arabic scanner interface with actual local OCR; extracted document values preserved');
  await db.user.update({ where: { id: user.id }, data: { role: 'OWNER' } });
  await page.reload();
  await page.goto('/app/owner');
  await expect(page.getByRole('heading', { name: 'لوحة المالك', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'المستخدمون', exact: true })).toBeVisible();
  await noOverflow();
  await page.screenshot({ path: '.data/display-owner-ar-mobile.png', fullPage: true, animations: 'disabled' });
  report.checks.push('Owner dashboard Arabic translation and mobile layout');
  await page.goto('/pricing');
  await expect(page.getByRole('button', { name: 'غير متاح للشراء حاليًا' })).toBeDisabled();
  await noOverflow();
  expect(errors).toEqual([]);
  await writeFile('.data/display-test-result.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} catch (error) {
  await page.screenshot({ path: '.data/display-failure.png', fullPage: true }).catch(() => {});
  throw error;
} finally {
  if (user) await db.user.update({ where: { id: user.id }, data: { role: 'USER' } });
  await db.$disconnect(); await browser.close();
}

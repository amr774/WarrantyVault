import { chromium, expect } from '@playwright/test';
import { randomBytes } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
const baseURL = process.env.SCANNER_TEST_URL ?? 'http://localhost:4173';
const browser = await chromium.launch();
const context = await browser.newContext({ baseURL });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  const email = `scanner-manual-${Date.now()}@example.com`;
  const registered = await context.request.post('/api/auth/register', { headers: { Origin: baseURL }, data: { name: 'Scanner manual test', email, password: randomBytes(24).toString('base64url') } });
  expect(registered.status(), await registered.text()).toBe(201);
  await page.goto('/app/products/new');
  await page.getByLabel('Product name').fill('Manual coverage verification');
  await page.getByLabel('Category').selectOption({ label: 'Electronics' });
  await page.getByLabel('Purchase date').fill('2026-10-15');
  await page.getByLabel('Warranty start date').fill('2026-11-15');
  await page.getByLabel('Warranty duration').fill('12');
  await page.getByRole('button', { name: 'Add to my vault' }).click();
  await expect(page.getByRole('heading', { name: 'Manual coverage verification' })).toBeVisible();
  const id = page.url().split('/').at(-1);
  const read = async () => (await context.request.get(`/api/products/${id}`)).json();
  expect((await read()).expiresAt.slice(0, 10)).toBe('2027-11-15');
  await page.getByRole('link', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Warranty start date').fill('');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(page).toHaveURL(new RegExp(`/products/${id}$`));
  expect((await read()).warrantyStartDate).toBe(null);
  expect((await read()).expiresAt.slice(0, 10)).toBe('2027-10-15');
  await page.goto('/app/scan');
  await page.getByLabel('Upload scan document').setInputFiles('tests/fixtures/ocr/english.pdf');
  await expect(page.getByRole('link', { name: 'Open original PDF' })).toBeVisible();
  await page.getByRole('button', { name: 'Start OCR' }).click();
  await expect(page.getByRole('heading', { name: 'Review before saving' })).toBeVisible({ timeout: 190000 });
  await expect(page.getByLabel('Product name', { exact: true })).toHaveValue('Studio Headphones');
  await expect(page.getByAltText('Original PDF page 1')).toBeVisible();
  await expect.poll(() => page.getByAltText('Original PDF page 1').evaluate(image => image.naturalWidth)).toBeGreaterThan(100);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '.data/scanner-review-mobile.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.screenshot({ path: '.data/scanner-review-pdf.png', fullPage: true });
  expect((await (await context.request.get('/api/products')).json()).total).toBe(1);
  expect(errors).toEqual([]);
  await writeFile('.data/scanner-ui-test-result.json', JSON.stringify({ email, productId: id, checks: ['Manual creation preserved', 'Explicit warranty start used for calculation', 'Clearing start date recalculates from purchase', 'PDF upload, preview element and OCR review', '390px mobile review without horizontal overflow', 'Unconfirmed scan not saved', 'No uncaught browser errors'] }, null, 2));
  console.log('Manual creation/editing and mobile PDF review passed. New test data retained.');
} finally { await browser.close(); }
